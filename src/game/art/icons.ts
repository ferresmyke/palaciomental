export const ICON_NAMES = Object.keys(ICONS);

export function drawIcon(p: Px, name: string, x: number, y: number, ramp: Ramp): void {
  const rows = ICONS[name] ?? ICONS.star;
  rows.forEach((row, j) => {
    for (let i = 0; i < row.length; i++) {
      const ch = row[i];
      if (ch === '.') continue;
      const c: Color = ch === '#' ? ramp[2] : ch === '+' ? ramp[4] : ramp[0];
      p.set(x + i, y + j, c);
    }
  });
}

const urlCache = new Map<string, string>();

/** Emblema como imagem (data URL) para a interface em HTML. */
export function iconUrl(name: string, color: keyof typeof R = 'reboco'): string {
  const key = `${name}:${color}`;
  let url = urlCache.get(key);
  if (!url) {
    const p = new Px(9, 9);
    drawIcon(p, name, 0, 0, R[color]);
    url = p.toCanvas().toDataURL();
    urlCache.set(key, url);
  }
  return url;
}
