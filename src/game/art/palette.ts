export type RampName = keyof typeof R;

/** Rampa pelo nome usado no catálogo; cai em `fallback` quando o nome não existe. */
export function ramp(name: string | null | undefined, fallback: RampName = 'carvalho'): Ramp {
  if (name && name in R) return R[name as RampName];
  return R[fallback];
}

